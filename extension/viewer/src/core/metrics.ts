/**
 * Release metrics: one registry, one recorder, one report (backlog N07).
 *
 * `docs/performance.md` (N06) measures a synthetic corpus and fails a budget; it
 * deliberately does not answer the release question, which is "what were startup, OCR,
 * translation, export and memory on the build we are about to ship?". This module is the
 * layer that question needs: a fixed set of metric names with a unit each, a recorder, a
 * snapshot with percentiles, a Markdown report, and a comparison that can contradict a
 * release note.
 *
 * Five rules shape it:
 *
 * 1. **The registry is the gate.** A metric is recorded by name, and a name that is not in
 *    {@link METRIC_DEFINITIONS} is an error rather than a new row; so is a unit that does
 *    not match the registry. `record('startup.ms', 900, 's')` is a thousand-fold mistake
 *    no later reader could detect, which is why it is refused at the door instead of
 *    written down.
 * 2. **Percentiles are `perf.ts`'s, not a second implementation.** p95 in a release report
 *    and p95 in the budget gate mean the same nearest-rank number, or the two documents
 *    disagree and neither is trustworthy. `max` and `min` are added here because a release
 *    decision wants the worst run, and p95 excludes it by construction.
 * 3. **A series is (metric, tags).** Two samples that differ in tags are different numbers
 *    and are never averaged into one: `startup.ms{mode=cold}` and `startup.ms{mode=warm}`
 *    answer different questions. Tag keys are sorted, and rows are ordered by registry
 *    order and then by canonical tag string, so two recorders that saw the same samples
 *    produce byte-identical snapshots.
 * 4. **Only latency and memory are graded.** A count (`ocr.pages`, `translate.blocks`) or a
 *    byte size (`export.bytes`) grows with the document, and calling that a regression
 *    would fail a release because the test document got bigger. Those rows are recorded as
 *    context and never graded; the definition's `graded` flag is the single place that
 *    judgement is written down.
 * 5. **No I/O, no DOM, no dependency.** Time is injected, so `recordedAt` is deterministic
 *    in a test and the table a document quotes can be regenerated byte for byte.
 *
 * What it does not do: it does not sample anything by itself, does not persist a history,
 * and does not aggregate across machines. The caller records; this module keeps the number
 * traceable to the run and the tags that produced it.
 */

import { PERCENTILE_DECIMALS, percentiles } from './perf';

// --- Registry --------------------------------------------------------------

/** Unit a metric is recorded in. Only the registry decides which metric uses which. */
export type MetricUnit = 'ms' | 'pages' | 'blocks' | 'bytes' | 'mb';

/**
 * Every metric a release note may cite, in the order reports list them.
 *
 * Adding a name here is the only way to record it, so this list is also the schema of a
 * release report: a metric that is missing from it cannot be measured, and one that is in
 * it has to be captured by something before a report is honest.
 */
export const METRIC_NAMES = [
  'startup.ms',
  'ocr.ms',
  'ocr.pages',
  'translate.ms',
  'translate.blocks',
  'export.ms',
  'export.bytes',
  'memory.mb',
  'search.ms',
] as const;

/** One registry name. Useful for typed call sites; {@link MetricsRecorder.record} takes `string`. */
export type MetricName = (typeof METRIC_NAMES)[number];

/** What the registry knows about a metric beyond its name. */
export interface MetricDefinition {
  readonly name: MetricName;
  /** The only unit this metric may be recorded in. */
  readonly unit: MetricUnit;
  /** One line: the number this metric records. */
  readonly summary: string;
  /** Where the value comes from, so a reader can go and look instead of trusting the table. */
  readonly source: string;
  /**
   * True when a rise in p95 is a release regression. Latency and memory are graded; counts
   * and byte sizes are context, because they grow with the document rather than with the build.
   */
  readonly graded: boolean;
}

/** Everything in a {@link MetricDefinition} except the name, which the order table supplies. */
type MetricMeta = Omit<MetricDefinition, 'name'>;

