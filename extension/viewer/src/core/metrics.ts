/** The registry, in report order. One row per name, enforced by `METRIC_META`'s type. */
export const METRIC_DEFINITIONS: readonly MetricDefinition[] = METRIC_NAMES.map(name => ({ name, ...METRIC_META[name] }));

const DEFINITION_BY_NAME = new Map<string, MetricDefinition>(METRIC_DEFINITIONS.map(definition => [definition.name, definition]));

const DEFINITION_ORDER = new Map<string, number>(METRIC_DEFINITIONS.map((definition, index) => [definition.name, index]));

/** Default cap on the samples one series keeps; a recorder lives for the whole app. */
export const DEFAULT_METRIC_CAPACITY = 10_000;

/** Default regression tolerance on p95, in percent. */
export const DEFAULT_TOLERANCE_PERCENT = 10;

/** Precision of a percentage this module prints, in decimal places. */
const PERCENT_DECIMALS = 1;

// --- Errors ----------------------------------------------------------------

export type MetricsErrorCode = 'unknown-metric' | 'unit-mismatch' | 'invalid-value' | 'invalid-tags';

/**
 * A recording a release report must not contain: a metric nobody defined, a unit that does
 * not match the registry, a value that is not a measurement, or tags that cannot be compared.
 *
 * All four are errors rather than warnings because every one of them produces a number that
 * looks fine in a table and means nothing.
 */
export class MetricsError extends Error {
  readonly code: MetricsErrorCode;
  /** The metric name the refusal is about; empty when the name itself is unusable. */
  readonly metric: string;

  constructor(code: MetricsErrorCode, metric: string, message: string) {
    super(message);
    this.name = 'MetricsError';
    this.code = code;
    this.metric = metric;
  }
}

// --- Snapshot --------------------------------------------------------------

/** Label values attached to a sample. Values are strings so rendering and matching are unambiguous. */
export type MetricTags = Readonly<Record<string, string>>;

/**
 * One (metric, tags) series as a snapshot reports it.
 *
 * `p50` and `p95` are `perf.ts`'s nearest-rank percentiles over every sample kept for this
 * series; `min` and `max` are added because p95 excludes the worst run on purpose.
 */
export interface MetricSeries {
  readonly name: MetricName;
  readonly unit: MetricUnit;
  /** Samples the percentiles were computed from. */
  readonly count: number;
  readonly p50: number;
  readonly p95: number;
  /** Largest sample kept. */
  readonly max: number;
  /** Smallest sample kept. */
  readonly min: number;
  /** Sorted by key. Every series has its own object, so no two rows share one. */
  readonly tags: MetricTags;
}

/** What one recording session knows. */
export interface MetricsSnapshot {
  /** Rows in registry order, then canonical tag order. One row per series with samples. */
  readonly metrics: readonly MetricSeries[];
  /** ISO-8601 timestamp of when `snapshot()` ran, from the recorder's injected clock. */
  readonly recordedAt: string;
}

export interface MetricsRecorderOptions {
  /**
   * Source of `recordedAt`. Defaults to the wall clock; a test passes a fixed date so the
   * report it asserts on can be pasted into a document unchanged.
   */
  now?: () => Date;
  /**
   * Samples kept per series; the oldest are dropped first. Defaults to
   * {@link DEFAULT_METRIC_CAPACITY}. `0` validates and stores nothing, which is a way to
   * leave recording wired up without paying for it.
   */
  capacity?: number;
}

/** Internal accumulator: one (metric, tags) series and its samples in recording order. */
interface Series {
  readonly key: string;
  readonly name: MetricName;
  readonly unit: MetricUnit;
  readonly tags: MetricTags;
  readonly values: number[];
}

const EMPTY_TAGS: MetricTags = Object.freeze({});

// --- Recorder --------------------------------------------------------------

/**
 * Records measurements against the registry.
 *
 * `record` refuses anything the registry cannot describe; `snapshot` groups by (name, tags)
 * and computes percentiles. Nothing is written anywhere: the caller decides where a snapshot
 * goes, which is what keeps this module usable from a test, a browser and the desktop shell.
 */
export class MetricsRecorder {
  readonly #series = new Map<string, Series>();
  readonly #now: () => Date;
  readonly #capacity: number;

  constructor(options: MetricsRecorderOptions = {}) {
    this.#now = typeof options.now === 'function' ? options.now : () => new Date();
    this.#capacity = readCapacity(options.capacity);
  }

  /**
   * Records one sample.
   *
   * Throws a {@link MetricsError} when `name` is not in the registry (`unknown-metric`), when
   * `unit` is not the unit the registry requires (`unit-mismatch`), when `value` is not a
   * finite, non-negative number (`invalid-value`), or when `tags` is not a flat object of
   * string values (`invalid-tags`). A negative or non-finite value is refused instead of
   * clamped to zero: a broken clock must not look like a fast run. `perf.ts` clamps for the
   * same reason it can — it measures, it does not testify.
   */
  record(name: string, value: number, unit: string, tags: MetricTags = EMPTY_TAGS): void {
    const definition = definitionFor(name);
    if (unit !== definition.unit) {
      throw new MetricsError(
        'unit-mismatch',
        definition.name,
        `${definition.name} is recorded in ${definition.unit}, not ${String(unit)}.`,
      );
    }
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
      throw new MetricsError(
        'invalid-value',
        definition.name,
        `${definition.name} needs a finite, non-negative number, got ${describeValue(value)}.`,
      );
    }
    const normalizedTags = readTags(tags, definition.name);
    if (this.#capacity === 0) return;

    const key = seriesKey(definition.name, normalizedTags);
    const existing = this.#series.get(key);
    if (existing) {
      existing.values.push(value);
      trim(existing.values, this.#capacity);
      return;
    }
    this.#series.set(key, {
      key,
      name: definition.name,
      unit: definition.unit,
      tags: normalizedTags,
      values: [value],
    });
  }

  /**
   * Everything recorded so far, as rows.
   *
   * Row order is registry order, then the canonical tag string, so it does not depend on the
   * order samples arrived in. `recordedAt` is read from the injected clock at call time, not
   * stored per sample: a snapshot describes when it was taken, which is what a report cites.
   */
  snapshot(): MetricsSnapshot {
    const rows: MetricSeries[] = [];
    const ordered = [...this.#series.values()].sort(compareSeries);

    for (const series of ordered) {
      if (series.values.length === 0) continue;
      const { p50, p95 } = percentiles(series.values);
      let max = 0;
      let min = Number.POSITIVE_INFINITY;
      for (const value of series.values) {
        if (value > max) max = value;
        if (value < min) min = value;
      }
      rows.push({
        name: series.name,
        unit: series.unit,
        count: series.values.length,
        p50,
        p95,
        max: roundTo(max, PERCENTILE_DECIMALS),
        min: roundTo(min, PERCENTILE_DECIMALS),
        tags: series.tags,
      });
    }

    return { metrics: rows, recordedAt: this.#now().toISOString() };
  }
}

// --- Report ----------------------------------------------------------------

export interface MarkdownReportOptions {
  /** Heading written above the table. Defaults to `Metrics snapshot`. */
  title?: string;
  /**
   * Baseline to compare against. When given, the report appends the regression table for the
   * metrics whose p95 rose over the tolerance, with the delta of each.
   */
  baseline?: MetricsSnapshot;
  /** Regression tolerance on p95, in percent. Defaults to {@link DEFAULT_TOLERANCE_PERCENT}. */
  tolerancePercent?: number;
}

/**
 * Renders a snapshot as the Markdown table a document quotes.
 *
 * The output is deterministic: no locale formatting, no sorting that depends on input order,
 * and tag text sanitised for a table cell. That is what lets `docs/metrics.md` paste the
 * output of the test fixture and have a test hold the two together.
 */
export function toMarkdownReport(snapshot: MetricsSnapshot, options: MarkdownReportOptions = {}): string {
  const title = nonEmpty(options.title) ?? 'Metrics snapshot';
  const rows = metricsOf(snapshot);
  const totalSamples = rows.reduce((sum, row) => sum + row.count, 0);
  const lines: string[] = [
    `### ${title}`,
    '',
    `Recorded at \`${recordedAtOf(snapshot)}\` — ${rows.length} series, ${countOf(totalSamples, 'sample')}.`,
    '',
    '| Metric | Unit | Samples | p50 | p95 | Max | Min | Tags |',
    '| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |',
  ];

  for (const row of rows) {
    lines.push(
      `| \`${row.name}\` | ${row.unit} | ${row.count} | ${number(row.p50)} | ${number(row.p95)} | ${number(row.max)} | ${number(row.min)} | ${tagsCell(row.tags)} |`,
    );
  }
  if (rows.length === 0) lines.push('| _(no samples recorded)_ | — | 0 | — | — | — | — | — |');

  if (options.baseline) {
    const comparison = compare(options.baseline, snapshot, { tolerancePercent: options.tolerancePercent });
    const tolerance = `${percent(comparison.tolerancePercent)}%`;
    const compared = `${comparison.compared} series compared`;
    lines.push('', `Baseline recorded at \`${recordedAtOf(options.baseline)}\`, compared at a ${tolerance} p95 tolerance.`, '');
    if (comparison.regressions.length === 0) {
      lines.push(`No regressions over the ${tolerance} p95 tolerance (${compared}).`);
    } else {
      lines.push(`${countOf(comparison.regressions.length, 'regression')} over the ${tolerance} p95 tolerance (${compared}):`, '');
      lines.push('| Metric | Unit | Baseline p95 | Current p95 | Delta | Tags |');
      lines.push('| --- | --- | ---: | ---: | ---: | --- |');
      for (const regression of comparison.regressions) {
        lines.push(
          `| \`${regression.name}\` | ${regression.unit} | ${number(regression.baselineP95)} | ${number(regression.currentP95)} | ${delta(regression.deltaPercent)} | ${tagsCell(regression.tags)} |`,
        );
      }
    }
    if (comparison.missingFromCurrent.length > 0) {
      lines.push('', `Not recorded in the current run: ${comparison.missingFromCurrent.map(name => `\`${name}\``).join(', ')}.`);
    }
  }

  return `${lines.join('\n')}\n`;
}

// --- Comparison ------------------------------------------------------------

/** One series whose p95 rose over the tolerance, with the delta that made it a regression. */
export interface Regression {
  readonly name: MetricName;
  readonly unit: MetricUnit;
  readonly tags: MetricTags;
  readonly baselineP95: number;
  readonly currentP95: number;
  /**
   * Percentage change of p95 relative to the baseline, rounded to three decimals, or `null`
   * when the baseline p95 was `0`: a metric measured at zero cannot rise by a percentage, so
   * any rise above zero is a regression and the report prints `n/a` for the delta.
   */
  readonly deltaPercent: number | null;
  /** Tolerance the comparison ran with, in percent. */
  readonly tolerancePercent: number;
}

/** The result of {@link compare}: what regressed, what was comparable, what stopped being recorded. */
export interface Comparison {
  /** Regressions in baseline row order. Empty is a real answer; check `compared` before citing it. */
  readonly regressions: readonly Regression[];
  /** Series present in both snapshots with the same tags. */
  readonly compared: number;
  /**
   * Registry names the baseline measured and the current snapshot did not record at all.
   * A series that exists with different tags is matched work with new labels, not a gap.
   */
  readonly missingFromCurrent: readonly MetricName[];
  readonly tolerancePercent: number;
}

export interface CompareOptions {
  /**
   * Tolerance on p95 growth, in percent. Defaults to {@link DEFAULT_TOLERANCE_PERCENT}.
   * A regression is strictly over it: a rise of exactly 10% passes a 10% tolerance, the same
   * way `perf.assertBudget` treats a p95 exactly on its budget. A negative or non-finite
   * tolerance falls back to the default rather than silently disabling the gate.
   */
  tolerancePercent?: number;
}

/**
 * Compares two snapshots on p95, series by series.
 *
 * Series are matched on the metric name *and* the full tag set: `translate.ms{engine=stub}`
 * and `translate.ms{engine=gpt}` are two different numbers, so a change of engine is not a
 * regression and not an improvement. Only `graded` metrics are examined; the rest are counted
 * in `compared` and otherwise ignored.
 *
 * `compared` is reported separately because zero regressions out of zero comparisons is the
 * most dangerous result this function can return, and it must not be mistaken for a pass.
 */
export function compare(baseline: MetricsSnapshot, current: MetricsSnapshot, options: CompareOptions = {}): Comparison {
  const tolerancePercent = readTolerance(options.tolerancePercent);
  const baselineRows = metricsOf(baseline);
  const currentRows = metricsOf(current);
  const currentByKey = new Map<string, MetricSeries>();
  const currentNames = new Set<string>();

  for (const row of currentRows) {
    currentNames.add(row.name);
    currentByKey.set(seriesKey(row.name, row.tags), row);
  }

  const missing = new Set<MetricName>();
  const regressions: Regression[] = [];
  let compared = 0;

  for (const row of baselineRows) {
    const match = currentByKey.get(seriesKey(row.name, row.tags));
    if (!match) {
      if (!currentNames.has(row.name)) missing.add(row.name);
      continue;
    }
    compared += 1;
    if (!isGraded(row.name)) continue;

    // Rises are checked by cross-multiplication, not by a computed percentage: `900 * 10 / 100`
    // is exact, so a rise of exactly the tolerance cannot be pushed over by float error.
    const rise = match.p95 - row.p95;
    const allowed = (row.p95 * tolerancePercent) / 100;
    if (!(rise > allowed)) continue;

    regressions.push({
      name: row.name,
      unit: row.unit,
      tags: row.tags,
      baselineP95: row.p95,
      currentP95: match.p95,
      deltaPercent: row.p95 > 0 ? roundTo((rise / row.p95) * 100, 3) : null,
      tolerancePercent,
    });
  }

  return {
    regressions,
    compared,
    missingFromCurrent: METRIC_NAMES.filter(name => missing.has(name)),
    tolerancePercent,
  };
}

// --- Internals -------------------------------------------------------------

/** The registry row for `name`, or a refusal that names the missing metric. */
function definitionFor(name: string): MetricDefinition {
  const definition = typeof name === 'string' ? DEFINITION_BY_NAME.get(name) : undefined;
  if (!definition) {
    throw new MetricsError(
      'unknown-metric',
      typeof name === 'string' ? name : '',
      `"${String(name)}" is not in the metric registry; add it to METRIC_DEFINITIONS with a unit, a summary and its source.`,
    );
  }
  return definition;
}

/** Copies the tags with sorted keys, refusing anything a comparison could not match. */
function readTags(tags: MetricTags | undefined | null, metric: MetricName): MetricTags {
  if (tags === undefined || tags === null) return EMPTY_TAGS;
  if (typeof tags !== 'object' || Array.isArray(tags)) {
    throw new MetricsError('invalid-tags', metric, `${metric} needs a tags object of string values, got ${describeValue(tags)}.`);
  }

  const entries = Object.entries(tags);
  if (entries.length === 0) return EMPTY_TAGS;
  for (const [key, value] of entries) {
    if (key.length === 0) throw new MetricsError('invalid-tags', metric, `${metric} has a tag with an empty key.`);
    if (typeof value !== 'string') {
      throw new MetricsError('invalid-tags', metric, `${metric} tag ${key} must be a string, got ${describeValue(value)}.`);
    }
  }
  entries.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0));
  // `Object.fromEntries` defines own data properties, so a `__proto__` tag stays a tag.
  return Object.fromEntries(entries);
}

/** Identity of a series: the metric name plus the canonical tag string. */
function seriesKey(name: string, tags: MetricTags): string {
  return `${name}\u0000${tagsKey(tags)}`;
}

/** Sorted `[key, value]` pairs as JSON, so two equal tag sets produce one string. */
function tagsKey(tags: MetricTags): string {
  const entries = Object.entries(tags ?? {}).map(([key, value]) => [key, String(value)] as [string, string]);
  entries.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0));
  return JSON.stringify(entries);
}

/** Registry order first, canonical tag string second: a snapshot does not depend on arrival order. */
function compareSeries(left: Series, right: Series): number {
  const byName = (DEFINITION_ORDER.get(left.name) ?? 0) - (DEFINITION_ORDER.get(right.name) ?? 0);
  if (byName !== 0) return byName;
  return left.key < right.key ? -1 : left.key > right.key ? 1 : 0;
}

function isGraded(name: MetricName): boolean {
  return DEFINITION_BY_NAME.get(name)?.graded ?? false;
}

function metricsOf(snapshot: MetricsSnapshot | undefined | null): readonly MetricSeries[] {
  return Array.isArray(snapshot?.metrics) ? (snapshot as MetricsSnapshot).metrics : [];
}

function recordedAtOf(snapshot: MetricsSnapshot | undefined | null): string {
  const value = snapshot?.recordedAt;
  return typeof value === 'string' && value.length > 0 ? value : 'unknown';
}

/** Keeps the newest `capacity` samples; `splice` on the array we own, no copy. */
function trim(values: number[], capacity: number): void {
  if (values.length > capacity) values.splice(0, values.length - capacity);
}

function readCapacity(value: unknown): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) return DEFAULT_METRIC_CAPACITY;
  return Math.max(0, Math.floor(value));
}

function readTolerance(value: unknown): number {
  if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) return DEFAULT_TOLERANCE_PERCENT;
  return value;
}

/** Rounds to `decimals` places, matching how `perf.ts` rounds its percentiles. */
function roundTo(value: number, decimals: number): number {
  const factor = 10 ** decimals;
  return Math.round(value * factor) / factor;
}

/** A number as the snapshot stores it: no thousands separators, no locale, so output is byte-stable. */
function number(value: number): string {
  return String(value);
}

/** A percentage with at most one decimal and no trailing `.0`. */
function percent(value: number): string {
  const rounded = roundTo(value, PERCENT_DECIMALS);
  return Number.isInteger(rounded) ? String(rounded) : rounded.toFixed(PERCENT_DECIMALS);
}

/** `+25%`, `-4.5%`, `0%`, or `n/a` for a rise a zero baseline cannot express. */
function delta(value: number | null): string {
  if (value === null) return 'n/a';
  const rounded = roundTo(value, PERCENT_DECIMALS);
  return `${rounded > 0 ? '+' : ''}${percent(rounded)}%`;
}

/** `1 sample` / `2 samples`; `series` is its own plural. */
function countOf(value: number, singular: string, plural = `${singular}s`): string {
  return `${value} ${value === 1 ? singular : plural}`;
}

/** Tag pairs as one cell, sorted, with the table's own metacharacters escaped. */
function tagsCell(tags: MetricTags): string {
  const entries = Object.entries(tags ?? {});
  if (entries.length === 0) return '—';
  const pairs = entries
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([key, value]) => `${key}=${value}`);
  return `\`${cell(pairs.join(', '))}\``;
}

/** Escapes the three characters that would end a table cell or a code span early. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/`/g, "'").replace(/[\r\n]+/g, ' ');
}

function nonEmpty(value: unknown): string | undefined {
  return typeof value === 'string' && value.trim().length > 0 ? value : undefined;
}

function describeValue(value: unknown): string {
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return JSON.stringify(value);
  return typeof value;
}
